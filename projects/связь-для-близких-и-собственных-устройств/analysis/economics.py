#!/usr/bin/env python3
"""Экономика «Предупреждение до перебоя» — воспроизводимый расчёт по учебным числам брифа [S001].
Запуск: python3 analysis/economics.py  → печать всех чисел, используемых в 04/06/Excel.
Ставка: 500 руб. валовой прибыли за один дополнительный оплаченный месяц одного номера [S001, C003].
"""
RATE = 500          # руб./доп. оплаченный месяц номера [S001]
PROFIT_GAP = 6_000_000   # руб.: цель 285 млн − «без изменений» 279 млн [S001]
TARGET_GROUPS = 12_000   # подключённых групп на конец планового года [S001]
TARGET_ACTIVE = 8_000    # активных групп за последний месяц [S001]
BASE_GROUPS = 6_500      # подключённые на конец базового года (оценка) [S001]
NOCHANGE_GROUPS = 8_000  # прогноз «без изменений» подключённых [S001]
NOCHANGE_ACTIVE = 5_000  # прогноз «без изменений» активных [S001]
NOCHANGE_PROFIT = 279_000_000

print("== Порог решения ==")
months_needed = PROFIT_GAP / RATE
print(f"Цель +6 млн руб. → {months_needed:,.0f} доп. оплаченных месяцев × {RATE} руб.".replace(",", " "))

print("\n== Сценарии вклада в прибыль (валовая прибыль = доп. мес × 500 руб. − прямые расходы) ==")
for label, numbers, months, direct in [
    ("Основной ход: 5 500 номеров × 3 мес, расходы 1,5 млн", 5_500, 3, 1_500_000),
    ("Сдержанный: 4 000 номеров × 3 мес, расходы 1,5 млн",   4_000, 3, 1_500_000),
    ("Минимальный: 6 000 номеров × 2 мес, расходы 0,5 млн",  6_000, 2,   500_000),
    ("Неблагоприятный: 3 000 номеров × 2 мес, расходы 1,5 млн", 3_000, 2, 1_500_000),
    ("Ноль: эффект не подтвердился (0 доп. мес), расходы 1,5 млн", 0, 0, 1_500_000),
    ("Минус: эффект ноль + отток организаторов (−2 000 мес), расходы 2,5 млн", 0, 0, 2_500_000),
]:
    gross = numbers * months * RATE
    net = gross - direct
    if label.startswith("Минус"): net -= 2_000 * RATE
    print(f"  {label}: вклад нетто {net/1e6:+.2f} млн → прибыль {NOCHANGE_PROFIT/1e6 + net/1e6:.2f} млн (цель 285)")

print("\n== Активность ==")
print(f"«Без изменений»: {NOCHANGE_ACTIVE} из {NOCHANGE_GROUPS} = {NOCHANGE_ACTIVE/NOCHANGE_GROUPS:.1%} [S001]")
print(f"При {TARGET_GROUPS} подключённых для {TARGET_ACTIVE} активных нужно {TARGET_ACTIVE/TARGET_GROUPS:.1%} групп")
print(f"Цель подключённых: чистый прирост {TARGET_GROUPS-BASE_GROUPS:,} к базовым {BASE_GROUPS:,}; разрыв к «без изменений» {TARGET_GROUPS-NOCHANGE_GROUPS:,}".replace(",", " "))

print("\n== Прогноз по 5 строкам (основной / менее благоприятный ход) ==")
rows = [
    ("Валовая прибыль, млн руб.", 285.8, 280.5, "вклад нетто 6,75 / 1,5 млн"),
    ("Подключённые группы на конец года", 11_500, 9_500, "привлечение в приложении/поддержке + снижение уходов"),
    ("Активные группы за последний месяц", 7_600, 6_400, "66% / 67% от подключённых (предупреждение подталкивает первое действие)"),
    ("Владельцы нескольких номеров на конец года", 1_200, 1_000, "вторая очередь в Q3–Q4 (перенос механики); без изменений до Q3"),
    ("Активация за 14 дней (последний квартал)", 0.60, 0.50, "предупреждение = повод для первого действия"),
]
for name, main, low, note in rows:
    fmt = lambda v: f"{v:,}".replace(",", " ")  # тысячи — пробелом; запятые заметки не трогаем
    print(f"  {name}: основной {fmt(main)} / неблагоприятный {fmt(low)} — {note}")
print("\nДля недостижимых целей: разрыв к цели и решение руководителя — см. 04, разд. «Прогноз» и 06.")
